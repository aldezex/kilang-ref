// Command gen writes token_kind.go, the Go source of the token kinds, from the
// list in token_kinds.txt. It runs through `go generate ./internal/syntax`
// (the directive lives in token.go) with the package directory as its working
// directory, so the list is read from the file of that name next to it.
//
// Every line of the list is `Name<tab>text`: the name of a kind and the fixed
// text of the token, empty for the kinds that have none (identifiers,
// literals, Newline, Eof and Error). The kinds become the constants of
// syntax.TokenKind, numbered in file order, and the kinds named KwXxx also go
// into the table that maps a keyword's text to its kind.
//
// Usage: go run ./gen [-o FILE]
//
// Without -o the source goes to stdout. The generated file is checked against
// that output by TestTokenKind/generated_file_is_up_to_date.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// inputFile is the list of kinds, relative to the working directory.
const inputFile = "token_kinds.txt"

// kind is one line of the list.
type kind struct {
	name string
	text string
}

func main() {
	out := flag.String("o", "", "write the generated source to this `file` instead of stdout")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintf(os.Stderr, "gen: unexpected argument %q\n", flag.Arg(0))
		os.Exit(2)
	}
	if err := run(*out); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

// run reads the list, generates the source and writes it to the file out, or
// to stdout when out is empty.
func run(out string) error {
	list, err := os.ReadFile(inputFile)
	if err != nil {
		return err
	}
	kinds, err := parse(string(list))
	if err != nil {
		return fmt.Errorf("%s: %v", inputFile, err)
	}
	src, err := generate(kinds)
	if err != nil {
		return err
	}
	if out == "" {
		_, err = os.Stdout.Write(src)
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// parse splits the list into kinds. Every line must be `Name<tab>text`, names
// must be unique, and a keyword (a name that starts with Kw) must have a text
// that no other keyword has: the keywords table maps each text to one kind, and
// a text twice would be a duplicate key that the generated file cannot compile.
func parse(list string) ([]kind, error) {
	var kinds []kind
	seen := make(map[string]bool)
	keywordOf := make(map[string]string) // the text of each keyword and its name
	for i, line := range strings.Split(strings.TrimSuffix(list, "\n"), "\n") {
		name, text, ok := strings.Cut(line, "\t")
		if !ok || name == "" {
			return nil, fmt.Errorf("line %d: want `Name<tab>text`, got %q", i+1, line)
		}
		if seen[name] {
			return nil, fmt.Errorf("line %d: %s is defined twice", i+1, name)
		}
		seen[name] = true
		if isKeyword(name) {
			if text == "" {
				return nil, fmt.Errorf("line %d: keyword %s has no text", i+1, name)
			}
			if other, ok := keywordOf[text]; ok {
				return nil, fmt.Errorf("line %d: keyword %s has the text %q, which %s has already", i+1, name, text, other)
			}
			keywordOf[text] = name
		}
		kinds = append(kinds, kind{name, text})
	}
	if len(kinds) > 256 {
		return nil, fmt.Errorf("%d kinds do not fit in a uint8", len(kinds))
	}
	return kinds, nil
}

// isKeyword reports whether the kind is a keyword: its name is Kw followed by
// the keyword with a capital letter, as in KwFn.
func isKeyword(name string) bool { return strings.HasPrefix(name, "Kw") }

// generate returns the gofmt-formatted source for kinds.
func generate(kinds []kind) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by `go run ./gen -o token_kind.go` from token_kinds.txt; DO NOT EDIT.\n\n")
	b.WriteString("package syntax\n\nimport \"strconv\"\n\n")

	b.WriteString("// TokenKind says what a token is: a keyword, a piece of punctuation, an\n")
	b.WriteString("// identifier, a literal or one of the markers Newline, Eof and Error.\n")
	b.WriteString("type TokenKind uint8\n\n")

	b.WriteString("// The token kinds, numbered in the order of token_kinds.txt.\n")
	b.WriteString("const (\n")
	for i, k := range kinds {
		if i == 0 {
			fmt.Fprintf(&b, "%s TokenKind = iota\n", k.name)
		} else {
			fmt.Fprintf(&b, "%s\n", k.name)
		}
	}
	b.WriteString(")\n\n")

	b.WriteString("// kindNames holds the name of every kind, indexed by the kind.\n")
	b.WriteString("var kindNames = [...]string{\n")
	for _, k := range kinds {
		fmt.Fprintf(&b, "%s: %q,\n", k.name, k.name)
	}
	b.WriteString("}\n\n")

	b.WriteString("// String returns the name of the kind as the source of this package spells it,\n")
	b.WriteString("// for example \"KwFn\" or \"LParen\". A value that is not a kind prints as\n")
	b.WriteString("// \"TokenKind(n)\".\n")
	b.WriteString("func (k TokenKind) String() string {\n")
	b.WriteString("if int(k) < len(kindNames) {\nreturn kindNames[k]\n}\n")
	b.WriteString("return \"TokenKind(\" + strconv.Itoa(int(k)) + \")\"\n}\n\n")

	b.WriteString("// keywords maps the text of every keyword to its kind.\n")
	b.WriteString("var keywords = map[string]TokenKind{\n")
	for _, k := range kinds {
		if isKeyword(k.name) {
			fmt.Fprintf(&b, "%q: %s,\n", k.text, k.name)
		}
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated source does not parse: %v", err)
	}
	return src, nil
}
